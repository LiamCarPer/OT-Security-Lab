#!/usr/bin/env python3
"""Poll the lab SNMP switch and emit normalized heartbeat events.

Writes the exporter-shape JSONL consumed by collector/sources/snmp.py and
pushes the same normalized line to Loki for the live rules. Heartbeats and
linkUp are benign; linkDown/restart are positive tests and are not generated by
this poller.
"""
import json
import subprocess
import time
import urllib.request
from datetime import datetime, timezone

SWITCH = "172.23.0.30"
OID = "1.3.6.1.2.1.1.3.0"
JSONL = "/logs/snmp-events.jsonl"
LOKI = "http://172.24.0.20:3100/loki/api/v1/push"


def poll():
    result = subprocess.run(
        ["snmpget", "-v2c", "-c", "otlab", "-Oqv", SWITCH, OID],
        capture_output=True,
        text=True,
        check=True,
        timeout=5,
    )
    value = result.stdout.strip().split()[0]
    moment = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    record = {
        "timestamp": moment,
        "device": SWITCH,
        "oid": OID,
        "value": value,
        "severity": "info",
    }
    with open(JSONL, "a", encoding="utf-8") as handle:
        handle.write(json.dumps(record) + "\n")
    push = (
        "event_type=heartbeat oid=%s snmp_value=%s severity=info"
        % (OID, value)
    ).encode()
    request = urllib.request.Request(
        LOKI, data=push, headers={"Content-Type": "text/plain"}
    )
    try:
        urllib.request.urlopen(request, timeout=3)
    except OSError:
        pass
    print(f"[snmp] {value}", flush=True)


while True:
    try:
        poll()
    except Exception as error:  # noqa: BLE001 - keep polling
        print(f"[snmp] {error}", flush=True)
    time.sleep(10)
